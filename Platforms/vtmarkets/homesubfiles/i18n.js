var currentLang = localStorage.getItem('vt_lang') || 'fr';

function selectLanguage(langCode, langLabel, el) {
    currentLang = langCode;
    localStorage.setItem('vt_lang', langCode);
    document.querySelectorAll('.lang-option').forEach(opt => opt.classList.remove('selected'));
    if (el) el.classList.add('selected');
    var dropdown = document.getElementById('langDropdown');
    if (dropdown) dropdown.classList.remove('active');
    
    applyLanguage(langCode);
    console.log('[Smart i18n] Switched language to:', langCode);
}

function applyLanguage(lang) {
    var dict = i18nDict[lang] || i18nDict.fr || i18nDict.en;
    document.documentElement.lang = lang;
    currentLang = lang;

    for (var key in dict) {
        var val = dict[key];
        
        // 1. Text elements
        var els = document.querySelectorAll('[data-i18n="' + key + '"]');
        els.forEach(function(el) {
            var svg = el.querySelector('svg');
            if (svg) {
                var span = el.querySelector('.menu-text') || el.querySelector('span');
                if (span) span.textContent = val;
            } else {
                el.textContent = val;
            }
        });

        // 2. Placeholders
        var placeholderEls = document.querySelectorAll('[data-i18n-placeholder="' + key + '"]');
        placeholderEls.forEach(function(el) {
            el.placeholder = val;
        });
    }

    // 3. Re-render Markets table to update headers and trade buttons
    if (typeof renderMarketsTable === 'function') {
        renderMarketsTable();
    }
    // The feed badge is written from JS, so data-i18n cannot reach it.
    if (typeof syncFeedStatus === 'function') {
        syncFeedStatus();
    }
}

document.addEventListener('DOMContentLoaded', function() {
    var lang = localStorage.getItem('vt_lang') || 'fr';
    applyLanguage(lang);
    document.querySelectorAll('.lang-option').forEach(function(opt) {
        if (opt.getAttribute('onclick') && opt.getAttribute('onclick').indexOf("'" + lang + "'") !== -1) {
            opt.classList.add('selected');
        } else {
            opt.classList.remove('selected');
        }
    });
});
